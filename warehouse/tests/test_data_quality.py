"""Data-quality tests the deck promises in the evidence pack ("Tests:
results of every data check"). These run against the synthetic sample data
generated by scripts/generate_sample_data.py.
"""
from __future__ import annotations

from pathlib import Path

import duckdb
import pytest

from ingestion.meter_reads import MAX_LATE_HOURS

DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "sample"


@pytest.fixture(scope="module")
def con():
    connection = duckdb.connect()
    yield connection
    connection.close()


def _load_sample(con, name: str):
    path = DATA_DIR / f"{name}.parquet"
    if not path.exists():
        pytest.skip(f"{path} not generated -- run scripts/generate_sample_data.py first")
    return con.execute(f"select * from read_parquet('{path.as_posix()}')").fetchdf()


def test_meter_reads_two_clocks_present(con):
    df = _load_sample(con, "meter_reads")
    assert "event_time" in df.columns
    assert "received_at" in df.columns
    # received_at must never be before event_time -- you can't receive a
    # reading before it happened.
    assert (df["received_at"] >= df["event_time"]).all()


def test_late_reads_bounded_by_stated_worst_case(con):
    df = _load_sample(con, "meter_reads")
    late_hours = (df["received_at"] - df["event_time"]).dt.total_seconds() / 3600
    # The deck states reads arrive up to 72 hours late. A read later than
    # that is either a data-gen bug or a real-world case the deck's
    # assumption doesn't cover -- either way, worth surfacing, not hiding.
    over_limit = (late_hours > MAX_LATE_HOURS).sum()
    assert over_limit / len(df) < 0.001, (
        f"{over_limit} of {len(df)} reads exceed the stated {MAX_LATE_HOURS}h "
        "late-read assumption -- re-check the assumption or the generator."
    )


def test_gis_link_error_rate_within_stated_range(con):
    df = _load_sample(con, "gis_network_map")
    if "is_wrong_link" not in df.columns:
        pytest.skip("sample generator does not tag wrong links in this build")
    error_rate = df["is_wrong_link"].mean()
    # Deck states 2-4% wrong meter-to-equipment links.
    assert 0.0 <= error_rate <= 0.08, (
        f"GIS wrong-link rate {error_rate:.3%} is far outside the deck's "
        "stated 2-4% range -- sample data no longer represents the "
        "documented assumption."
    )


def test_asset_blank_failure_cause_rate_matches_deck(con):
    df = _load_sample(con, "asset_management")
    blank_rate = df["failure_cause"].isin(["", "other"]).mean()
    # Deck states 60% of work orders have blank/"other" failure cause --
    # this is the gap crew-note extraction exists to fill.
    assert blank_rate > 0.3, (
        f"Sample blank/other failure-cause rate is {blank_rate:.1%}, much "
        "lower than the deck's stated 60% -- crew-note extraction's "
        "business case depends on this gap being real."
    )
