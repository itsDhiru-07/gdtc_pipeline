"""Smart meter reads — 2.1M meters, 15-minute interval, late up to 72 hours.

Source: AMI head-end system (SaaS, outside this platform).
Lands to C1 (governance/data_classification.yaml) — own KMS key, no standing
analyst access, 13-month retention.

Late and corrected reads are the deck's part-4 problem: a correction never
overwrites a prior row. It lands as a new row with the ORIGINAL event_time and
a NEW received_at. Downstream, "as of" queries pick the row that was known at
cutoff — see warehouse/models/staging/stg_meter_reads.sql.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import pandas as pd

from ingestion.base import LandedBatch, land

MAX_LATE_HOURS = 72  # per the deck's stated worst case


def fetch_meter_reads(source_df: pd.DataFrame, as_of: datetime) -> pd.DataFrame:
    """Simulate pulling whatever the AMI head-end has available right now.

    `source_df` already carries event_time per row (generated by
    scripts/generate_sample_data.py, including deliberately late rows).
    received_at is stamped at fetch time, not at event_time, which is the
    whole point: this is what makes late data late.
    """
    df = source_df.copy()
    df["received_at"] = as_of
    df["source"] = "ami_head_end"
    late_hours = (df["received_at"] - df["event_time"]).dt.total_seconds() / 3600
    df["is_late"] = late_hours > 1  # anything not landing within the same hour
    df["late_hours"] = late_hours.clip(lower=0)
    return df


def run(source_df: pd.DataFrame, as_of: datetime, out_dir: Path) -> LandedBatch:
    df = fetch_meter_reads(source_df, as_of)
    return land(df, source="meter_reads", out_dir=out_dir, received_at=as_of)
